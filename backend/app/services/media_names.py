"""File names of web-uploaded media and the values of media fields (media_upload plan D2 step 4, D3).

網頁上傳媒體的檔名與媒體欄位的值（media_upload 計畫書 D2 第 4 步、D3）。

- File names are always generated by the backend: ``web_{kind}_{UTC time}_{6 random chars}.{extension}``.
  AnkiConnect's ``storeMediaFile`` silently overwrites a file with the same name, so using the user's file name
  would overwrite someone else's file.
- A media field (the handler's ``MEDIA_FIELDS``) accepts only a name in this format whose extension belongs to the
  field's kind (or the current value, or blank): the service layer does not trust the frontend and rejects
  hand-typed names as well as TG and script file names (``rec_``, ``avatar_`` and so on). **Only the format is
  checked**; it does not confirm that the file really exists in Anki, so a well-formed but missing name passes and
  the card simply cannot play it. When written to Anki the name is wrapped as ``[sound:name]`` or
  ``<img src="name">`` according to its kind (Anki's convention; card templates display it directly).

- 檔名一律由後端產生：``web_{種類}_{UTC 時間}_{隨機 6 碼}.{副檔名}``。AnkiConnect 的 ``storeMediaFile``
  遇到同名檔會直接覆蓋，採用使用者的檔名會蓋掉別人的檔案。
- 媒體欄位（handler 的 ``MEDIA_FIELDS``）只能填符合這個命名格式、副檔名屬於該種類的檔名（或原值、
  空白）：服務層不相信前端，擋掉手打的名字與 TG、腳本的檔名（``rec_``、``avatar_`` 等）。**只檢查格式**，
  不確認檔案真的在 Anki 裡——格式正確但不存在的名字會通過，卡片上只是播不出來。
  寫進 Anki 時依種類包成 ``[sound:檔名]`` 或 ``<img src="檔名">``（Anki 的慣例，卡片模板直接顯示）。

This module has no external dependencies (it touches neither Anki nor ffmpeg), so ``task_handlers`` can import it
directly.

這個模組沒有外部相依（不碰 Anki、ffmpeg），``task_handlers`` 可以直接引用。
"""

from __future__ import annotations

import re
import secrets
from datetime import UTC, datetime
from typing import Literal, get_args

from app.core.exceptions import MediaFieldInvalidError

#: The kinds of media.
#: 媒體的種類。
MediaKind = Literal["audio", "image"]

#: Every kind (used by declaration checks).
#: 所有種類（宣告檢查用）。
MEDIA_KINDS: tuple[str, ...] = get_args(MediaKind)

#: The extensions stored in Anki per kind: ``media_service.ACCEPTED_FORMATS`` minus the ones that get converted
#: (webm, m4a), plus mp3. The two must agree (a test checks this), or an upload succeeds but is rejected when put
#: into a field.
#: 各種類存進 Anki 的副檔名：``media_service.ACCEPTED_FORMATS`` 扣掉要轉檔的（webm、m4a），加上 mp3。
#: 兩邊要一致（有測試檢查），否則上傳成功、填進欄位時卻被拒。
STORED_EXTENSIONS: dict[str, tuple[str, ...]] = {
    "audio": ("mp3", "ogg", "wav"),
    "image": ("jpg", "png", "webp"),
}

#: The names ``new_media_name`` produces. Uses ``[0-9]`` rather than ``\d``, because ``\d`` also matches
#: full-width digits.
#: ``new_media_name`` 產生的檔名。用 ``[0-9]`` 而不是 ``\d``：``\d`` 也會匹配全形數字。
_UPLOADED_NAME = re.compile(r"web_(audio|image)_[0-9]{8}_[0-9]{6}_[0-9a-f]{6}\.([a-z0-9]+)")


def new_media_name(kind: MediaKind, extension: str) -> str:
    """Generate a new file name (D2 step 4).

    產生一個新的檔名（D2 第 4 步）。

    The time is accurate to the second, followed by 6 random hex digits (about 16.77 million values), so even
    uploads in the same second almost never collide. The extension is not validated here.

    時間精確到秒，再加 6 碼隨機十六進位（約 1,677 萬種），同一秒上傳也幾乎不會撞名。這裡不檢查副檔名。

    Args:
        kind: the media kind
            媒體種類
        extension: the extension without the dot; must be in ``STORED_EXTENSIONS[kind]``
            副檔名（不含點），要在 ``STORED_EXTENSIONS[kind]`` 內

    Returns:
        the name, for example ``web_audio_20261020_153012_3f9a1c.mp3``
        檔名，例如 ``web_audio_20261020_153012_3f9a1c.mp3``
    """
    stamp = datetime.now(tz=UTC).strftime("%Y%m%d_%H%M%S")
    return f"web_{kind}_{stamp}_{secrets.token_hex(3)}.{extension}"


def uploaded_media_kind(name: str) -> MediaKind | None:
    """Return the kind of a name in the format ``POST /media`` produces, or ``None`` for any other name.

    檔名若是 ``POST /media`` 產生的格式，回傳它的種類；否則為 ``None``。

    A name whose extension is not in ``STORED_EXTENSIONS`` for its kind also yields ``None``.

    副檔名不在該種類的 ``STORED_EXTENSIONS`` 內的檔名，也回傳 ``None``。

    Args:
        name: the file name
            檔名

    Returns:
        the kind, or ``None``
        種類，或 ``None``
    """
    match = _UPLOADED_NAME.fullmatch(name)
    if match is None:
        return None
    kind, extension = match.group(1), match.group(2)
    if extension not in STORED_EXTENSIONS[kind]:
        return None
    return kind  # type: ignore[return-value]


def wrap_media(kind: MediaKind, name: str) -> str:
    """Wrap a file name in Anki's field markup.

    把檔名包成 Anki 欄位的寫法。

    Args:
        kind: the media kind
            媒體種類
        name: the file name, already checked by ``uploaded_media_kind`` (only letters, digits, underscores and dots)
            檔名（``uploaded_media_kind`` 檢查過的，只有英數、底線與點）

    Returns:
        ``[sound:name]`` or ``<img src="name">``
        ``[sound:檔名]`` 或 ``<img src="檔名">``
    """
    return f"[sound:{name}]" if kind == "audio" else f'<img src="{name}">'


def media_field_text(field: str, kind: MediaKind, value: object, current: str = "") -> str:
    """Return the text a media field should store in Anki (D3 "the service layer checks again").

    回傳媒體欄位要寫進 Anki 的值（D3「服務層再檢查一次」）。

    - Identical to the field's current value: unchanged (a field left untouched during an edit).
    - Blank (``None`` or whitespace only): clear the field.
    - A name produced by ``POST /media`` whose kind matches the field: wrapped in Anki's markup.
    - Anything else is rejected.

    - 和欄位原本的值一樣：不變（修改時沒動到的欄位）。
    - 空白（``None`` 或只有空白字元）：清空欄位。
    - ``POST /media`` 產生的檔名，而且種類和欄位一致：包成 Anki 的寫法。
    - 其他一律拒絕。

    Args:
        field: the field name (used in error messages)
            欄位名（錯誤訊息用）
        kind: this field's media kind
            這個欄位的媒體種類
        value: the submitted value
            送來的值
        current: the field's current value; an empty string when creating
            欄位原本的值；建立時為空字串

    Returns:
        the text to write
        要寫入的字串

    Raises:
        MediaFieldInvalidError: if the value is not an uploaded name, or its kind does not match
            若不是上傳取得的檔名，或種類不符
    """
    text = "" if value is None else str(value)
    if text == current:
        return current
    name = text.strip()
    if not name:
        return ""
    found = uploaded_media_kind(name)
    label = "音檔" if kind == "audio" else "圖片"
    if found is None:
        raise MediaFieldInvalidError(f"「{field}」只能填在網頁上傳{label}後取得的檔名，不能自己輸入：{name[:80]}")
    if found != kind:
        raise MediaFieldInvalidError(f"「{field}」要的是{label}，不能填{'圖片' if found == 'image' else '音檔'}：{name}")
    return wrap_media(kind, name)
