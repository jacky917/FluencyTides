"""
網頁上傳媒體的檔名與媒體欄位的值（media_upload 計畫書 D2 第 4 步、D3）。

File names of web-uploaded media and the values of media fields.

- 檔名一律由後端產生：``web_{種類}_{UTC 時間}_{隨機 6 碼}.{副檔名}``。AnkiConnect 的 ``storeMediaFile``
  遇到同名檔會直接覆蓋，採用使用者的檔名會蓋掉別人的檔案。
- 媒體欄位（handler 的 ``MEDIA_FIELDS``）只能填符合這個命名格式、副檔名屬於該種類的檔名（或原值、
  空白）：服務層不相信前端，擋掉手打的名字與 TG、腳本的檔名（``rec_``、``avatar_`` 等）。**只檢查格式**，
  不確認檔案真的在 Anki 裡——格式正確但不存在的名字會通過，卡片上只是播不出來。
  寫進 Anki 時依種類包成 ``[sound:檔名]`` 或 ``<img src="檔名">``（Anki 的慣例，卡片模板直接顯示）。

這個模組沒有外部相依（不碰 Anki、ffmpeg），``task_handlers`` 可以直接引用。

Names are generated by the backend, and media fields accept only such
names; they are wrapped in Anki's markup when written.
"""

from __future__ import annotations

import re
import secrets
from datetime import UTC, datetime
from typing import Literal, get_args

from app.core.exceptions import MediaFieldInvalidError

#: 媒體的種類。The kinds of media.
MediaKind = Literal["audio", "image"]

#: 所有種類（宣告檢查用）。Every kind.
MEDIA_KINDS: tuple[str, ...] = get_args(MediaKind)

#: 各種類存進 Anki 的副檔名：``media_service.ACCEPTED_FORMATS`` 扣掉要轉檔的（webm、m4a），加上 mp3。
#: 兩邊要一致（有測試檢查），否則上傳成功、填進欄位時卻被拒。Stored extensions per kind.
STORED_EXTENSIONS: dict[str, tuple[str, ...]] = {
    "audio": ("mp3", "ogg", "wav"),
    "image": ("jpg", "png", "webp"),
}

#: ``new_media_name`` 產生的檔名。用 ``[0-9]`` 而不是 ``\d``：``\d`` 也會匹配全形數字。
#: The names ``new_media_name`` produces.
_UPLOADED_NAME = re.compile(r"web_(audio|image)_[0-9]{8}_[0-9]{6}_[0-9a-f]{6}\.([a-z0-9]+)")


def new_media_name(kind: MediaKind, extension: str) -> str:
    """產生一個新的檔名（D2 第 4 步）。A new file name.

    時間精確到秒，再加 6 碼隨機十六進位（約 1,677 萬種），同一秒上傳也幾乎不會撞名。

    Args:
        kind: 媒體種類。The kind.
        extension: 副檔名（不含點），要在 ``STORED_EXTENSIONS[kind]`` 內。The extension.

    Returns:
        檔名，例如 ``web_audio_20261020_153012_3f9a1c.mp3``。The name.
    """
    stamp = datetime.now(tz=UTC).strftime("%Y%m%d_%H%M%S")
    return f"web_{kind}_{stamp}_{secrets.token_hex(3)}.{extension}"


def uploaded_media_kind(name: str) -> MediaKind | None:
    """檔名若是 ``POST /media`` 產生的格式，回傳它的種類；否則為 None。

    The kind of a name produced by ``POST /media``, or None for any other name.

    Args:
        name: 檔名。The name.

    Returns:
        種類，或 None。The kind, or None.
    """
    match = _UPLOADED_NAME.fullmatch(name)
    if match is None:
        return None
    kind, extension = match.group(1), match.group(2)
    if extension not in STORED_EXTENSIONS[kind]:
        return None
    return kind  # type: ignore[return-value]


def wrap_media(kind: MediaKind, name: str) -> str:
    """把檔名包成 Anki 欄位的寫法。Wraps a name in Anki's field markup.

    Args:
        kind: 媒體種類。The kind.
        name: 檔名（``uploaded_media_kind`` 檢查過的，只有英數、底線與點）。The name.

    Returns:
        ``[sound:檔名]`` 或 ``<img src="檔名">``。The markup.
    """
    return f"[sound:{name}]" if kind == "audio" else f'<img src="{name}">'


def media_field_text(field: str, kind: MediaKind, value: object, current: str = "") -> str:
    """媒體欄位要寫進 Anki 的值（D3「服務層再檢查一次」）。The text to store in a media field.

    - 空白：清空欄位。
    - 和欄位原本的值一樣：不變（修改時沒動到的欄位）。
    - ``POST /media`` 產生的檔名，而且種類和欄位一致：包成 Anki 的寫法。
    - 其他一律拒絕。

    Args:
        field: 欄位名（錯誤訊息用）。The field name.
        kind: 這個欄位的媒體種類。The field's kind.
        value: 送來的值。The submitted value.
        current: 欄位原本的值；建立時為空字串。The field's current value.

    Returns:
        要寫入的字串。The text to write.

    Raises:
        MediaFieldInvalidError: 不是上傳取得的檔名，或種類不符。Not an uploaded name of this kind.
    """
    text = "" if value is None else str(value)
    if text == current:
        return current
    name = text.strip()
    if not name:
        return ""
    found = uploaded_media_kind(name)
    label = "音檔" if kind == "audio" else "圖片"
    if found is None:
        raise MediaFieldInvalidError(f"「{field}」只能填在網頁上傳{label}後取得的檔名，不能自己輸入：{name[:80]}")
    if found != kind:
        raise MediaFieldInvalidError(f"「{field}」要的是{label}，不能填{'圖片' if found == 'image' else '音檔'}：{name}")
    return wrap_media(kind, name)
